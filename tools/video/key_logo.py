"""Key the opaque black background out of the damaged Stack logos and measure their alignment
against the healthy logo (assets/video/stack_logo.png, transparent bg).

  python3 tools/video/key_logo.py

Outputs (all reproducible, deterministic):
  assets/video/stack_logo_hurt_key.png      keyed stack_logo_hurt.png
  assets/video/stack_logo_hurt_alt_key.png  keyed stack_logo_hurt_alt.png
  tools/video/logo_align.js                 scale/offset that lays each keyed hurt logo over the healthy one

Keying: flood fill from every border pixel through near-black pixels (max channel <= TOL), so only
background connected to the image edge is removed; the dark outline (max channel >= ~12) stops the fill.
The binary mask is then softened with a small blur (FEATHER px) for a 1-2 px anti-aliased edge.
Alignment: grid search of scale + offset that maximises the IoU of the two alpha masks (downsampled)."""
import json, os
from collections import deque
from PIL import Image, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
VID = os.path.join(ROOT, "assets", "video")
TOL = 9          # max(r,g,b) <= TOL counts as background (bg noise is 0..3, outline is >= 12)
FEATHER = 0.8    # gaussian radius of the soft edge
SRC = {"hurt": "stack_logo_hurt.png", "hurt_alt": "stack_logo_hurt_alt.png"}


def key(path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = im.tobytes()
    bg = bytearray(w * h)
    q = deque()

    def dark(i):
        return max(px[3 * i], px[3 * i + 1], px[3 * i + 2]) <= TOL

    for x in range(w):
        for y in (0, h - 1):
            q.append(y * w + x)
    for y in range(h):
        for x in (0, w - 1):
            q.append(y * w + x)
    while q:
        i = q.popleft()
        if bg[i] or not dark(i):
            continue
        bg[i] = 1
        x, y = i % w, i // w
        if x > 0: q.append(i - 1)
        if x < w - 1: q.append(i + 1)
        if y > 0: q.append(i - w)
        if y < h - 1: q.append(i + w)
    mask = Image.frombytes("L", (w, h), bytes(0 if b else 255 for b in bg))
    out = im.convert("RGBA")
    out.putalpha(mask.filter(ImageFilter.GaussianBlur(FEATHER)))
    return out


def alpha_mask(img, size):
    return [1 if v > 127 else 0 for v in img.getchannel("A").resize((size, size), Image.BILINEAR).tobytes()]


def align(healthy, hurt):
    """Find s, dx, dy (in source px, about the image centre) so that hurt placed with scale s and offset
    (dx, dy) overlaps healthy best: IoU grid search, coarse at 160 px then refined at 320 px."""
    W = healthy.size[0]
    iou, s, dx, dy = search(healthy, hurt, 160, [1.0 + i * 0.01 for i in range(-12, 13)], range(-8, 9), range(-10, 11), 0, 0)
    return search(healthy, hurt, 320, [s + i * 0.0025 for i in range(-4, 5)], range(-3, 4), range(-3, 4), dx * 320 / W, dy * 320 / W)


def search(healthy, hurt, n, scales, dxs, dys, cx, cy):
    W = healthy.size[0]
    a = alpha_mask(healthy, n)
    best = (-1, 1.0, 0, 0)
    for s in scales:
        m = int(round(n * s))
        hb = hurt.getchannel("A").resize((m, m), Image.BILINEAR).tobytes()
        for dyi in dys:
            for dxi in dxs:
                ox = int(round((n - m) / 2 + cx)) + dxi
                oy = int(round((n - m) / 2 + cy)) + dyi
                inter = uni = 0
                for y in range(n):
                    sy = y - oy
                    row = y * n
                    for x in range(n):
                        sx = x - ox
                        b = 1 if (0 <= sx < m and 0 <= sy < m and hb[sy * m + sx] > 127) else 0
                        av = a[row + x]
                        inter += av & b
                        uni += av | b
                iou = inter / uni
                if iou > best[0]:
                    best = (iou, s, (ox - (n - m) / 2) * W / n, (oy - (n - m) / 2) * W / n)
    return best


def main():
    healthy = Image.open(os.path.join(VID, "stack_logo.png")).convert("RGBA")
    res = {}
    for name, f in SRC.items():
        k = key(os.path.join(VID, f))
        out = os.path.join(VID, f.replace(".png", "_key.png"))
        k.save(out, optimize=True)
        iou, s, dx, dy = align(healthy, k)
        res[name] = {"scale": round(s, 3), "dx": round(dx, 1), "dy": round(dy, 1), "iou": round(iou, 3)}
        print(f"{out}: scale={s:.3f} dx={dx:.1f} dy={dy:.1f} iou={iou:.3f}")
    js = os.path.join(ROOT, "tools", "video", "logo_align.js")
    with open(js, "w") as fh:
        fh.write("// generated by tools/video/key_logo.py: draw the keyed hurt logo at this scale/offset (source px,\n"
                 "// about the image centre) over the healthy logo so a crossfade reads as the same stack.\n")
        fh.write("window.LOGO_ALIGN = " + json.dumps(res, indent=2) + ";\n")
    print(js)


if __name__ == "__main__":
    main()
